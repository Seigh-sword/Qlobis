//! Web backend: AST -> TSX/TS sources + standalone JS + CSS + HTML.
//!
//! Output layout (`qlob/web/`):
//! * `src/program.ts`  — typed TypeScript of the transpiled program
//! * `src/App.tsx`, `src/main.tsx` — React shell (build with `npm run build`)
//! * `js/program.js`, `js/app.js` — plain-JS runtime (open `index.html`)
//! * `index.html`, `styles.css`, `package.json`, `tsconfig.json`

