//! Native backend: optimized IR -> C++17, compiled by an external compiler.
//!
//! The emitted project is `qlobis_runtime.h` + `program.cpp`. The build system
//! invokes `clang++`/`g++`/`cl` afterwards.

use super::GenFile;
use qlobis_ast::{BinOp, Type, UnOp};
use qlobis_ir::passes::optimize;
use qlobis_ir::lower::lower;
use qlobis_ir::{CallTarget, IrFunc, IrProgram, RValue, Stmt, StrPiece};
use qlobis_tyck::Target;
use std::collections::HashMap;

pub fn generate(input: &super::GenInput) -> Vec<GenFile> {
    let mut program = lower(input.modules, input.checked, Target::Native, input.entry);
    optimize(&mut program);
    let mut emitter = CppEmitter {
        generic_env: HashMap::new(),
        slots: Vec::new(),
        out: String::new(),
    };
    emitter.emit_program(&program, input.package);
    vec![
        GenFile {
            path: "qlobis_runtime.h".to_string(),
            contents: RUNTIME_H.to_string(),
        },
        GenFile {
            path: "program.cpp".to_string(),
            contents: emitter.out,
        },
    ]
}

/// Map a Qlobis type to its C++ spelling.
pub fn cpp_type_of(t: &Type) -> String {
    cpp_type_env(t, &HashMap::new())
}

fn cpp_type_env(t: &Type, env: &HashMap<String, String>) -> String {
    match t {
        Type::Int => "int64_t".to_string(),
        Type::Float => "double".to_string(),
        Type::Str => "std::string".to_string(),
        Type::Bool => "bool".to_string(),
        Type::None => "qlob::None".to_string(),
        Type::Any => "qlob::Any".to_string(),
        Type::List(inner) => format!("std::vector<{}>", cpp_type_env(inner, env)),
        Type::Map(k, v) => format!(
            "std::map<{}, {}>",
            cpp_type_env(k, env),
            cpp_type_env(v, env)
        ),
        Type::Struct(name, args) => {
            if let Some(mapped) = env.get(name) {
                return mapped.clone();
            }
            if args.is_empty() {
                name.clone()
            } else {
                format!(
                    "{}<{}>",
                    name,
                    args.iter()
                        .map(|a| cpp_type_env(a, env))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            }
        }
        Type::Fn(ps, r) => format!(
            "std::function<{}({})>",
            if matches!(**r, Type::None) {
                "void".to_string()
            } else {
                cpp_type_env(r, env)
            },
            ps.iter()
                .map(|p| cpp_type_env(p, env))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Type::Var(_) => "auto".to_string(),
    }
}

struct CppEmitter {
    generic_env: HashMap<String, String>,
    slots: Vec<(String, Type)>,
    out: String,
}

impl CppEmitter {
    fn ty(&self, t: &Type) -> String {
        cpp_type_env(t, &self.generic_env)
    }

    fn emit_program(&mut self, p: &IrProgram, package: &str) {
        self.out.push_str("// Generated by the Qlobis compiler.\n");
        self.out.push_str(&format!("// Package: {}\n", package));
        self.out.push_str("#include \"qlobis_runtime.h\"\n\n");

        // Forward declarations of free functions.
        for f in &p.funcs {
            self.generic_env.clear();
            self.emit_signature(f, true);
            self.out.push_str(";\n");
        }
        self.out.push('\n');

        // Structs (with inline method bodies).
        for s in &p.structs {
            self.generic_env.clear();
            for g in &s.generics {
                self.generic_env.insert(g.clone(), g.clone());
            }
            if !s.generics.is_empty() {
                self.out.push_str(&format!(
                    "template<{}>\n",
                    s.generics
                        .iter()
                        .map(|g| format!("typename {}", g))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
            self.out.push_str(&format!("struct {} {{\n", s.name));
            for (fname, fty) in &s.fields {
                self.out
                    .push_str(&format!("    {} {};\n", self.ty(fty), fname));
            }
            for m in &s.methods {
                self.out.push('\n');
                self.emit_signature(m, false);
                self.out.push_str(" {\n");
                self.emit_body(m);
                self.out.push_str("    }\n");
            }
            self.out.push_str("};\n\n");
        }
        self.generic_env.clear();

        // Free function definitions.
        for f in &p.funcs {
            self.generic_env.clear();
            self.emit_signature(f, true);
            self.out.push_str(" {\n");
            self.emit_body(f);
            self.out.push_str("}\n\n");
        }

        // Entry.
        if let Some(entry) = &p.entry {
            self.out.push_str("int main() {\n");
            self.out.push_str("    try {\n");
            let entry_fn = p.funcs.iter().find(|f| f.name == *entry);
            let is_async = entry_fn.map(|f| f.is_async).unwrap_or(false);
            let ret_int = entry_fn.map(|f| f.ret == Type::Int).unwrap_or(false);
            if is_async {
                if ret_int {
                    self.out
                        .push_str(&format!("        int64_t code = {}().get();\n", entry));
                    self.out.push_str("        return (int)code;\n");
                } else {
                    self.out.push_str(&format!("        {}().get();\n", entry));
                }
            } else if ret_int {
                self.out
                    .push_str(&format!("        return (int) {}();\n", entry));
            } else {
                self.out.push_str(&format!("        {}();\n", entry));
            }
            self.out.push_str("    } catch (const qlob::QlobError& e) {\n");
            self.out
                .push_str("        std::cerr << \"error: \" << e.what() << \"\\n\";\n");
            self.out.push_str("        return 1;\n");
            self.out.push_str("    }\n");
            self.out.push_str("}\n");
        }
    }

    fn emit_signature(&mut self, f: &IrFunc, free: bool) {
        // Locals table for slot lookup.
        self.slots = f.locals.clone();
        // Function's own generic parameters.
        for g in &f.generics {
            self.generic_env.insert(g.clone(), g.clone());
        }
        if !f.generics.is_empty() {
            self.out.push_str(&format!(
                "template<{}>\n",
                f.generics
                    .iter()
                    .map(|g| format!("typename {}", g))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        let ret = match &f.ret {
            Type::None if f.is_async => "std::future<void>".to_string(),
            Type::None => "void".to_string(),
            t if f.is_async => format!("std::future<{}>", self.ty(t)),
            t => self.ty(t),
        };
        let params: Vec<String> = f
            .params
            .iter()
            .filter(|(n, _)| n != "self")
            .map(|(n, t)| format!("{} {}", self.ty(t), n))
            .collect();
        if free {
            self.out.push_str(&format!(
                "static {} {}({})",
                ret,
                f.name,
                params.join(", ")
            ));
        } else {
            // Methods keep their original name inside the struct.
            let mname = f.qual_name.rsplit("::").next().unwrap_or(&f.name);
            self.out
                .push_str(&format!("    {} {}({})", ret, mname, params.join(", ")));
        }
    }

    /// Emit a function body; `async` functions run theirs inside `std::async`
    /// and hand back a `std::future`.
    fn emit_body(&mut self, f: &IrFunc) {
        if f.is_async {
            let inner = match &f.ret {
                Type::None => "void".to_string(),
                t => self.ty(t),
            };
            self.out.push_str(&format!(
                "    return std::async(std::launch::async, [=]() -> {} {{\n",
                inner
            ));
            self.emit_block(&f.body, 2);
            self.out.push_str("    });\n");
        } else {
            self.emit_block(&f.body, 1);
        }
    }

    fn emit_block(&mut self, stmts: &[Stmt], indent: usize) {
        for s in stmts {
            self.emit_stmt(s, indent);
        }
    }

    fn ind(&mut self, indent: usize) {
        for _ in 0..indent {
            self.out.push_str("    ");
        }
    }

    fn emit_stmt(&mut self, s: &Stmt, indent: usize) {
        match s {
            Stmt::Let(slot, v) => {
                let (name, ty) = self.slot_info(*slot);
                let val = self.rvalue(v);
                self.ind(indent);
                if uses_generic(&ty, &self.generic_env) {
                    self.out.push_str(&format!("auto {} = {};\n", name, val));
                } else {
                    self.out
                        .push_str(&format!("{} {} = {};\n", self.ty(&ty), name, val));
                }
            }
            Stmt::Assign(slot, v) => {
                let (name, _) = self.slot_info(*slot);
                let val = self.rvalue(v);
                self.ind(indent);
                self.out.push_str(&format!("{} = {};\n", name, val));
            }
            Stmt::AssignCompound(slot, op, v) => {
                let (name, _) = self.slot_info(*slot);
                let val = self.rvalue(v);
                self.ind(indent);
                self.out
                    .push_str(&format!("{} {}= {};\n", name, op.as_str(), val));
            }
            Stmt::AssignIndex(recv, idx, val) => {
                let r = self.rvalue(recv);
                let i = self.rvalue(idx);
                let v = self.rvalue(val);
                self.ind(indent);
                self.out
                    .push_str(&format!("qlob::list_set({}, {}, {});\n", r, i, v));
            }
            Stmt::AssignField(recv, field, val) => {
                let r = self.rvalue(recv);
                let v = self.rvalue(val);
                self.ind(indent);
                self.out.push_str(&format!("{}.{} = {};\n", r, field, v));
            }
            Stmt::Expr(v) => {
                let e = self.rvalue(v);
                self.ind(indent);
                self.out.push_str(&format!("{};\n", e));
            }
            Stmt::Scope(b) => {
                self.ind(indent);
                self.out.push_str("{\n");
                self.emit_block(b, indent + 1);
                self.ind(indent);
                self.out.push_str("}\n");
            }
            Stmt::If(c, t, e) => {
                let cond = self.rvalue(c);
                self.ind(indent);
                self.out.push_str(&format!("if ({}) {{\n", cond));
                self.emit_block(t, indent + 1);
                if !e.is_empty() {
                    self.ind(indent);
                    self.out.push_str("} else {\n");
                    self.emit_block(e, indent + 1);
                }
                self.ind(indent);
                self.out.push_str("}\n");
            }
            Stmt::While(c, b) => {
                let cond = self.rvalue(c);
                self.ind(indent);
                self.out.push_str(&format!("while ({}) {{\n", cond));
                self.emit_block(b, indent + 1);
                self.ind(indent);
                self.out.push_str("}\n");
            }
            Stmt::For(slot, it, b) => {
                let (name, vty) = self.slot_info(*slot);
                let iter = self.rvalue(it);
                self.ind(indent);
                if matches!(vty, Type::Map(..)) {
                    // Iterate keys.
                    self.out
                        .push_str(&format!("for (const auto& __kv : {}) {{\n", iter));
                    self.ind(indent + 1);
                    self.out
                        .push_str(&format!("const auto& {} = __kv.first;\n", name));
                } else {
                    self.out
                        .push_str(&format!("for (const auto& {} : {}) {{\n", name, iter));
                }
                self.emit_block(b, indent + 1);
                self.ind(indent);
                self.out.push_str("}\n");
            }
            Stmt::Return(v) => {
                self.ind(indent);
                match v {
                    Some(v) => {
                        let e = self.rvalue(v);
                        self.out.push_str(&format!("return {};\n", e));
                    }
                    None => self.out.push_str("return;\n"),
                }
            }
            Stmt::Throw(v) => {
                let e = self.rvalue(v);
                self.ind(indent);
                self.out
                    .push_str(&format!("throw qlob::QlobError(qlob::to_str({}));\n", e));
            }
            Stmt::Try { body, var, catch } => {
                self.ind(indent);
                self.out.push_str("try {\n");
                self.emit_block(body, indent + 1);
                self.ind(indent);
                self.out.push_str("} catch (const std::exception& __qlob_exc) {\n");
                if let Some(slot) = var {
                    let (name, _) = self.slot_info(*slot);
                    self.ind(indent + 1);
                    self.out
                        .push_str(&format!("std::string {} = __qlob_exc.what();\n", name));
                }
                self.emit_block(catch, indent + 1);
                self.ind(indent);
                self.out.push_str("}\n");
            }
            Stmt::Break => {
                self.ind(indent);
                self.out.push_str("break;\n");
            }
            Stmt::Continue => {
                self.ind(indent);
                self.out.push_str("continue;\n");
            }
        }
    }

    // Slot info is threaded via the current function; kept in a side channel.
    fn slot_info(&self, slot: u32) -> (String, Type) {
        self.slots
            .get(slot as usize)
            .cloned()
            .unwrap_or_else(|| (format!("v{}", slot), Type::Any))
    }

    fn rvalue(&mut self, v: &RValue) -> String {
        match v {
            RValue::Int(n) => format!("INT64_C({})", n),
            RValue::Float(f) => {
                let s = format!("{}", f);
                if s.contains('.') || s.contains('e') {
                    s
                } else {
                    format!("{}.0", s)
                }
            }
            RValue::Bool(b) => (if *b { "true" } else { "false" }).to_string(),
            RValue::None => "qlob::None{}".to_string(),
            RValue::Str(pieces) => {
                let mut acc: Option<String> = None;
                for p in pieces {
                    let piece = match p {
                        StrPiece::Lit(s) => format!("\"{}\"", escape_cpp_str(s)),
                        StrPiece::Expr(e) => {
                            let e = self.rvalue(e);
                            format!("qlob::to_str({})", e)
                        }
                    };
                    acc = Some(match acc {
                        None => piece,
                        Some(prev) => format!("({} + {})", prev, piece),
                    });
                }
                acc.unwrap_or_else(|| "std::string()".to_string())
            }
            RValue::Local(slot) => {
                let (name, _) = self.slot_info(*slot);
                if name == "self" {
                    "(*this)".to_string()
                } else {
                    name
                }
            }
            RValue::FuncRef(name) => name.clone(),
            RValue::List(items, ty) => {
                let inner: Vec<String> = items.iter().map(|i| self.rvalue(i)).collect();
                let lty = self.ty(ty);
                format!("{}{{{}}}", lty, inner.join(", "))
            }
            RValue::Map(entries, ty) => {
                let inner: Vec<String> = entries
                    .iter()
                    .map(|(k, val)| {
                        format!("{{{}, {}}}", self.rvalue(k), self.rvalue(val))
                    })
                    .collect();
                let mty = self.ty(ty);
                format!("{}{{{}}}", mty, inner.join(", "))
            }
            RValue::StructCtor(name, args, ty) => {
                let inner: Vec<String> = args.iter().map(|a| self.rvalue(a)).collect();
                let sty = self.ty(ty);
                format!("{}{{{}}}", sty, inner.join(", "))
            }
            RValue::Binary(op, a, b, ty) => self.binary(op, a, b, ty),
            RValue::Unary(op, a, _) => {
                let x = self.rvalue(a);
                match op {
                    UnOp::Neg => format!("(-{})", x),
                    UnOp::Not => format!("(!{})", x),
                    UnOp::BitNot => format!("(~{})", x),
                }
            }
            RValue::Await(a, _) => {
                let x = self.rvalue(a);
                format!("qlob::await_get({})", x)
            }
            RValue::Index(recv, idx, _) => {
                let r = self.rvalue(recv);
                let i = self.rvalue(idx);
                format!("qlob::list_get({}, {})", r, i)
            }
            RValue::Field(recv, name, _) => {
                let r = self.rvalue(recv);
                format!("{}.{}", r, name)
            }
            RValue::Method {
                recv,
                name,
                args,
                ret: _,
                builtin,
            } => {
                let r = self.rvalue(recv);
                let mut argv: Vec<String> = args.iter().map(|a| self.rvalue(a)).collect();
                if !*builtin {
                    return format!("{}.{}({})", r, name, argv.join(", "));
                }
                argv.insert(0, r);
                format!("qlob::{}({})", cpp_method_name(name), argv.join(", "))
            }
            RValue::Call(target, args, ret) => {
                let argv: Vec<String> = args.iter().map(|a| self.rvalue(a)).collect();
                match target {
                    CallTarget::Func(name) => {
                        if matches!(ret, Type::None) {
                            format!("{}({})", name, argv.join(", "))
                        } else {
                            format!("{}({})", name, argv.join(", "))
                        }
                    }
                    CallTarget::Intrinsic(name) => {
                        format!("qlob::{}({})", cpp_intrinsic(name), argv.join(", "))
                    }
                    CallTarget::Builtin(name) => match name.as_str() {
                        "int" => format!("qlob::conv_int({})", argv.join(", ")),
                        "float" => format!("qlob::conv_float({})", argv.join(", ")),
                        "str" => format!("qlob::to_str({})", argv.join(", ")),
                        "bool" => format!("qlob::conv_bool({})", argv.join(", ")),
                        "range" => format!("qlob::range_of({})", argv.join(", ")),
                        other => format!("/* builtin {} */({})", other, argv.join(", ")),
                    },
                    CallTarget::Host(name) => format!("{}({})", name, argv.join(", ")),
                    CallTarget::Indirect => {
                        let callee = argv.first().cloned().unwrap_or_default();
                        let rest = argv[1..].join(", ");
                        format!("{}({})", callee, rest)
                    }
                }
            }
        }
    }

    fn binary(&mut self, op: &BinOp, a: &RValue, b: &RValue, ty: &Type) -> String {
        let x = self.rvalue(a);
        let y = self.rvalue(b);
        let lt = a.ty();
        let rt = b.ty();
        match op {
            BinOp::Add => {
                if matches!(ty, Type::Str) {
                    // At least one operand is a string; to_str is identity on
                    // strings, so this is correct for every combination.
                    format!("(qlob::to_str({}) + qlob::to_str({}))", x, y)
                } else {
                    let _ = (lt, rt);
                    format!("({} + {})", x, y)
                }
            }
            BinOp::Div => {
                // Operand `.ty()` is `Any` for locals; the RESULT type is
                // authoritative (int/int -> int, anything else -> float).
                if matches!(ty, Type::Int) {
                    format!("qlob::idiv({}, {})", x, y)
                } else {
                    format!("((double)({}) / (double)({}))", x, y)
                }
            }
            BinOp::Mod => {
                if matches!(ty, Type::Int) {
                    format!("qlob::imod({}, {})", x, y)
                } else {
                    format!("std::fmod((double)({}), (double)({}))", x, y)
                }
            }
            BinOp::And => format!("({} && {})", x, y),
            BinOp::Or => format!("({} || {})", x, y),
            BinOp::Eq => format!("qlob::eq({}, {})", x, y),
            BinOp::Ne => format!("(!qlob::eq({}, {}))", x, y),
            _ => {
                let _ = ty;
                format!("({} {} {})", x, op.as_str(), y)
            }
        }
    }
}

fn uses_generic(t: &Type, env: &HashMap<String, String>) -> bool {
    match t {
        Type::Struct(name, args) => {
            env.contains_key(name) || args.iter().any(|a| uses_generic(a, env))
        }
        Type::List(inner) => uses_generic(inner, env),
        Type::Map(k, v) => uses_generic(k, env) || uses_generic(v, env),
        Type::Fn(ps, r) => ps.iter().any(|p| uses_generic(p, env)) || uses_generic(r, env),
        _ => false,
    }
}

fn cpp_method_name(name: &str) -> String {
    format!("m_{}", name)
}

fn cpp_intrinsic(name: &str) -> String {
    match name {
        "__print" => "print".to_string(),
        "__println" => "println".to_string(),
        "__input" => "input".to_string(),
        "__fs_read" => "fs_read".to_string(),
        "__fs_write" => "fs_write".to_string(),
        "__fs_list" => "fs_list".to_string(),
        "__fs_exists" => "fs_exists".to_string(),
        "__fs_remove" => "fs_remove".to_string(),
        "__fs_mkdir" => "fs_mkdir".to_string(),
        "__net_get" => "net_get".to_string(),
        "__net_post" => "net_post".to_string(),
        "__time_now_ms" => "now_ms".to_string(),
        "__exit" => "qexit".to_string(),
        "__parallel_map" => "parallel_map".to_string(),
        "__thread_count" => "thread_count".to_string(),
        other => other.trim_start_matches('_').to_string(),
    }
}

fn escape_cpp_str(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\x{:02x}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

