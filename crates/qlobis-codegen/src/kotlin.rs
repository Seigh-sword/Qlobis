//! Kotlin backend: AST -> Kotlin sources for the mobile target.
//!
//! Type mapping: `int` -> `Long`, `float` -> `Double`, `str` -> `String`,
//! `bool` -> `Boolean`, `list<T>` -> `MutableList<T>`, `map<K,V>` ->
//! `MutableMap<K,V>`.  `async` maps to `suspend fun` driven by a small
//! run-blocking helper built on `kotlin.coroutines` (stdlib only).

